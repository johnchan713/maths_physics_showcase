def postwave_mean_envelope(n,old_rows,old_scalars,cov,cov_next,fixed):
    """Keep full old rows/scalars and add complete current covariance change.

    cov dominates all six through n+3 for pointwise graph rows. cov_next
    dominates the n+1 Haar scalar request; conservative larger norms may
    be used. Full moving T0 pressure is recomputed before target projection.
    """
    order(n)
    delta=current.mean.fast.covariance_rows(n,cov,fixed)
    scal=current.mean.scalar.wave_change(n,cov,cov_next,fixed['Kmom'])
    return dict(rows={k:old_rows[k]+delta[k] for k in ('Etheta','Ez')},
                scalars={k:old_scalars[k]+scal[k] for k in ('P','Jtheta','Jz')},
                complete_pressure_change=delta,scalar_change=scal)
